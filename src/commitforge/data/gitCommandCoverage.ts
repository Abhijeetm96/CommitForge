export function calculateCommandCoverage(): CoverageStats {
  const totalCommands = GIT_COMMAND_COVERAGE.length;
  let tier1Count = 0;
  let tier2Count = 0;
  let tier3Count = 0;
  let tier4Count = 0;
  let engineSupportedCount = 0;
  let visualizedCount = 0;
  let testedCount = 0;

  for (const item of GIT_COMMAND_COVERAGE) {
    if (item.tier === 'Tier 1') tier1Count++;
    else if (item.tier === 'Tier 2') tier2Count++;
    else if (item.tier === 'Tier 3') tier3Count++;
    else if (item.tier === 'Tier 4') tier4Count++;

    if (item.supportedByEngine) engineSupportedCount++;
    if (item.visualized) visualizedCount++;
    if (item.tested) testedCount++;
  }

  // Coverage percentage is calculated as the ratio of supported/simulated/visualized commands
  const coveragePercentage = Math.round((engineSupportedCount / totalCommands) * 100);

  return {
    totalCommands,
    tier1Count,
    tier2Count,
    tier3Count,
    tier4Count,
    engineSupportedCount,
    visualizedCount,
    testedCount,
    coveragePercentage,
  };
}
