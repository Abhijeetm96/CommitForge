export function getAllRoadmapItems(): RoadmapItem[] {
  const result: RoadmapItem[] = [];
  function traverse(item: RoadmapItem) {
    result.push(item);
    if (item.subItems) {
      item.subItems.forEach(traverse);
    }
  }
  ROADMAP_SECTIONS.forEach((section) => {
    section.milestones.forEach(traverse);
  });
  return result;
}

export function searchRoadmap(query: string): RoadmapItem[] {
  if (!query.trim()) return [];
  const q = query.toLowerCase().trim();
  const all = getAllRoadmapItems();
  return all.filter((item) => {
    const matchLabel = item.label.toLowerCase().includes(q);
    const matchDesc = item.description.toLowerCase().includes(q);
    const matchCategory = item.category.toLowerCase().includes(q);
    const matchCommands = item.commands?.some((c) => c.toLowerCase().includes(q));
    return matchLabel || matchDesc || matchCategory || matchCommands;
  });
}
